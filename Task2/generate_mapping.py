# ---------- Вспомогательные функции ----------
def is_stop_word(word):
    return word.lower() in STOP_WORDS

def random_math_word(target_len=None):
    """Возвращает случайный математический термин (с модификацией) примерно нужной длины."""
    if not MATH_WORDS:
        return "математика"
    word = random.choice(MATH_WORDS)
    # Если длина не задана, возвращаем как есть (иногда модифицируем)
    if target_len is None:
        return modify_word(word)
    # Ищем слово, близкое по длине
    candidates = [w for w in MATH_WORDS if abs(len(w) - target_len) <= 2]
    if not candidates:
        candidates = MATH_WORDS
    base = random.choice(candidates)
    # Модифицируем, чтобы получить точную длину (если нужно)
    return adjust_length(modify_word(base), target_len)

def modify_word(word):
    """Вносит случайные изменения в слово (перестановка, замена гласной, суффикс)."""
    if len(word) < 2:
        return word + random.choice(['р', 'н', 'л', 'м'])
    chars = list(word)
    # Перестановка двух случайных букв
    if len(chars) > 1:
        i, j = random.sample(range(len(chars)), 2)
        chars[i], chars[j] = chars[j], chars[i]
    # Замена одной гласной
    vowels = 'аеёиоуыэюя'
    for idx, ch in enumerate(chars):
        if ch.lower() in vowels:
            new_vowel = random.choice(vowels)
            if new_vowel != ch:
                chars[idx] = new_vowel
                break
    # Добавление случайного суффикса (с вероятностью 0.3)
    if random.random() < 0.3:
        suffix = random.choice(['р', 'н', 'л', 'м', 'ст', 'в', 'к'])
        chars.append(suffix)
    new_word = ''.join(chars)
    # Если получилось исходное слово, добавляем суффикс
    if new_word == word:
        new_word = word + random.choice(['р', 'н', 'л', 'м'])
    return new_word

def adjust_length(word, target_len):
    """Подгоняет слово к заданной длине (обрезает или дополняет случайными буквами)."""
    if len(word) == target_len:
        return word
    if len(word) > target_len:
        return word[:target_len]
    else:
        letters = 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя'
        missing = target_len - len(word)
        for _ in range(missing):
            word += random.choice(letters)
        return word

def generate_new_word(original_word, used_replacements):
    """Генерирует новое слово для замены оригинального, не совпадающее с использованными."""
    target_len = len(original_word)
    for _ in range(50):
        candidate = random_math_word(target_len)
        if candidate != original_word and candidate not in used_replacements:
            return candidate
    # Fallback: добавляем суффикс к оригиналу (это не должно случиться)
    return original_word + random.choice(['р', 'н', 'л', 'м'])

def apply_word_mapping(text, word_mapping):
    """Заменяет слова в тексте согласно word_mapping (ключи в нижнем регистре)."""
    pattern = re.compile(r"[А-Яа-яA-Za-z']+")
    def replace_match(match):
        word = match.group(0)
        lower_word = word.lower()
        if lower_word in word_mapping:
            replacement = word_mapping[lower_word]
            if word.isupper():
                return replacement.upper()
            elif word.istitle():
                return replacement.capitalize()
            else:
                return replacement.lower()
        else:
            return word
    return pattern.sub(replace_match, text)

def generate_unique_mapping_for_category(names, max_attempts=200):
    """Генерирует словарь замен для категории, гарантируя уникальность."""
    # Извлекаем все уникальные знаменательные слова
    unique_words = set()
    for name in names:
        if isinstance(name, str):
            found = re.findall(r"[А-Яа-яA-Za-z']+", name)
            for w in found:
                if not is_stop_word(w):
                    unique_words.add(w.lower())

    if len(unique_words) < 1:
        return {}

    # Для каждого уникального слова подбираем замену
    word_mapping = {}
    used_replacements = set()
    for w in unique_words:
        new_w = generate_new_word(w, used_replacements)
        word_mapping[w] = new_w
        used_replacements.add(new_w)

    # Применяем замены ко всем названиям категории и проверяем уникальность
    for attempt in range(max_attempts):
        new_names = []
        for original in names:
            new_name = apply_word_mapping(original, word_mapping)
            new_names.append(new_name)

        if len(set(new_names)) == len(new_names):
            return {original: new_name for original, new_name in zip(names, new_names)}

        # Перегенерируем замены для всех слов
        word_mapping = {}
        used_replacements = set()
        for w in unique_words:
            new_w = generate_new_word(w, used_replacements)
            word_mapping[w] = new_w
            used_replacements.add(new_w)

    # Крайний случай – добавляем суффиксы
    print(f"⚠️ Не удалось достичь уникальности за {max_attempts} попыток. Добавляем суффиксы.")
    final_mapping = {}
    used_names = set()
    for original, new_name in zip(names, new_names):
        base = new_name
        counter = 1
        while new_name in used_names:
            new_name = f"{base}_{counter}"
            counter += 1
        used_names.add(new_name)
        final_mapping[original] = new_name
    return final_mapping

def generate_mapping(entities_by_category):
    final_mapping = {}
    for category, names in entities_by_category.items():
        category_mapping = generate_unique_mapping_for_category(names)
        final_mapping.update(category_mapping)
        print(f"✅ Категория '{category}': {len(category_mapping)} замен.")
    return final_mapping

def load_entities(json_path):
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    entities_by_category = {}
    for category, items in data.items():
        if category == "даты_и_события":
            events = [item["событие"] for item in items if isinstance(item, dict) and "событие" in item]
            if events:
                entities_by_category[category] = events
        elif isinstance(items, list):
            strings = [item for item in items if isinstance(item, str)]
            if strings:
                entities_by_category[category] = strings
    return entities_by_category

def main():
    parser = argparse.ArgumentParser(description='Генерирует словарь замен на основе математических терминов (300+ слов).')
    parser.add_argument('json_file', help='Путь к исходному JSON')
    parser.add_argument('-o', '--output', default='mapping.json', help='Выходной JSON')
    args = parser.parse_args()

    entities = load_entities(args.json_file)
    if not entities:
        print("Не найдено сущностей для генерации.")
        return

    mapping = generate_mapping(entities)

    with open(args.output, 'w', encoding='utf-8') as f:
        json.dump(mapping, f, ensure_ascii=False, indent=2)

    print(f"✅ Сгенерировано {len(mapping)} пар. Сохранено в {args.output}")

if __name__ == "__main__":
    main()
